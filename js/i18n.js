let currentLang = 'vi';

export function setLanguage(lang) {
  if (TRANSLATIONS[lang]) {
    currentLang = lang;
    localStorage.setItem('ws_lang', lang);
  }
}

export function getLanguage() {
  return currentLang;
}

export function t(key) {
  return TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS['vi']?.[key] || key;
}
